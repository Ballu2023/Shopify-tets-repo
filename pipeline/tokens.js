#!/usr/bin/env node
// Turns inputs/style-guide.json into <theme>/assets/bot-tokens.css and links it in layout/theme.liquid.
// Every custom section the bots build wraps itself in class="bot-ui" and uses these variables and classes.
const fs = require('fs');
const path = require('path');
const { P, config, readJSON } = require('./lib');

const sg = readJSON(P.styleGuide, null);
if (!sg) { console.error('ERROR: inputs/style-guide.json missing or invalid JSON'); process.exit(1); }
const cfg = config();
if (!cfg.themeDir) { console.error('ERROR: theme folder not found (needs config/settings_schema.json)'); process.exit(1); }
const theme = path.join(P.root, cfg.themeDir);

const px = v => (typeof v === 'number' ? v + 'px' : v);
// Map a literal colour from the style guide back to its token var, so generated CSS has no stray hex.
const _cmap = new Map(Object.entries(sg.colors || {}).map(([k, v]) => [String(v).trim().toLowerCase(), k]));
const cv = v => { const k = _cmap.get(String(v).trim().toLowerCase()); return k ? `var(--bot-color-${k})` : v; };
const L = [];
const fonts = Object.values(sg.fonts || {}).filter(f => f.google);
if (fonts.length) {
  const fam = fonts.map(f => 'family=' + f.family.replace(/ /g, '+') + ':wght@' + (f.weights || [400]).join(';')).join('&');
  L.push(`@import url('https://fonts.googleapis.com/css2?${fam}&display=swap');`);
}
L.push('/* Generated by pipeline/tokens.js from inputs/style-guide.json. Do not edit by hand. */', ':root {');
for (const [k, v] of Object.entries(sg.colors || {})) L.push(`  --bot-color-${k}: ${v};`);
if (sg.fonts?.heading) L.push(`  --bot-font-heading: '${sg.fonts.heading.family}', system-ui, sans-serif;`);
if (sg.fonts?.body) L.push(`  --bot-font-body: '${sg.fonts.body.family}', system-ui, sans-serif;`);
if (sg.fonts?.script) L.push(`  --bot-font-script: '${sg.fonts.script.family}', cursive;`);
for (const [k, v] of Object.entries(sg.spacing || {})) L.push(`  --bot-space-${k}: ${px(v)};`);
for (const [k, v] of Object.entries(sg.radius || {})) L.push(`  --bot-radius-${k}: ${px(v)};`);
for (const [k, v] of Object.entries(sg.shadows || {})) L.push(`  --bot-shadow-${k}: ${v};`);
// Form tokens as variables too, so sections outside .bot-ui can reuse them instead of hard-coding.
if (sg.forms) {
  const f2 = sg.forms;
  if (f2.inputHeight != null) L.push(`  --bot-form-input-height: ${px(f2.inputHeight)};`);
  if (f2.inputRadius != null) L.push(`  --bot-form-input-radius: ${px(f2.inputRadius)};`);
  if (f2.inputBorder) L.push(`  --bot-form-input-border: ${cv(f2.inputBorder)};`);
  if (f2.focusColor) L.push(`  --bot-form-focus-color: ${cv(f2.focusColor)};`);
}
for (const [tag, t] of Object.entries(sg.typography || {})) {
  const d = t.desktop || {}, m = t.mobile || {};
  L.push(`  --bot-${tag}-size: ${px(m.size || d.size)};`, `  --bot-${tag}-lh: ${m.lineHeight || d.lineHeight};`);
}
L.push('}');
L.push(`@media (min-width: ${(sg.breakpoints?.tablet || 768)}px) {`, '  :root {');
for (const [tag, t] of Object.entries(sg.typography || {})) {
  const d = t.desktop || {};
  L.push(`    --bot-${tag}-size: ${px(d.size)};`, `    --bot-${tag}-lh: ${d.lineHeight};`);
}
L.push('  }', '}');

// Scoped base styles: only inside .bot-ui so Horizon's own sections are untouched.
L.push(`.bot-ui { font-family: var(--bot-font-body); color: var(--bot-color-text); }`);
L.push(`:where(.bot-ui) .bot-container { max-width: var(--bot-space-containerMax); margin-inline: auto; padding-inline: var(--bot-space-gutterMobile); }`);
L.push(`@media (min-width: ${(sg.breakpoints?.tablet || 768)}px) { :where(.bot-ui) .bot-container { padding-inline: var(--bot-space-gutterDesktop); } }`);
L.push(`:where(.bot-ui).bot-section { padding-block: var(--bot-space-sectionMobile); }`);
L.push(`@media (min-width: ${(sg.breakpoints?.tablet || 768)}px) { :where(.bot-ui).bot-section { padding-block: var(--bot-space-sectionDesktop); } }`);
for (const [tag, t] of Object.entries(sg.typography || {})) {
  const d = t.desktop || {};
  const isHeading = /^h[1-6]$/.test(tag);
  const sel = `:where(.bot-ui) ${tag}, :where(.bot-ui) .bot-${tag}`;
  L.push(`${sel} { font-family: var(${isHeading ? '--bot-font-heading' : '--bot-font-body'}); font-size: var(--bot-${tag}-size); line-height: var(--bot-${tag}-lh); font-weight: ${d.weight || 400}; letter-spacing: ${px(d.letterSpacing || 0)}; ${d.textTransform ? 'text-transform: ' + d.textTransform + ';' : ''} ${isHeading ? 'color: var(--bot-color-heading); margin: 0 0 0.5em;' : ''} }`);
}
for (const [name, b] of Object.entries(sg.buttons || {})) {
  L.push(`:where(.bot-ui) .bot-btn-${name} { display: inline-flex; align-items: center; justify-content: center; gap: 8px; min-height: 44px; background: ${cv(b.background)}; color: ${cv(b.text)}; border: ${px(b.borderWidth ?? 1)} solid ${cv(b.border)}; border-radius: ${px(b.radius)}; padding: ${px(b.paddingY)} ${px(b.paddingX)}; font-family: var(--bot-font-body); font-size: ${px(b.fontSize)}; font-weight: ${b.fontWeight}; text-transform: ${b.textTransform || 'none'}; text-decoration: none; cursor: pointer; transition: background .2s, color .2s, border-color .2s; }`);
  if (b.hover) L.push(`:where(.bot-ui) .bot-btn-${name}:hover { background: ${cv(b.hover.background)}; color: ${cv(b.hover.text)}; border-color: ${cv(b.hover.border)}; }`);
  L.push(`:where(.bot-ui) .bot-btn-${name}:focus-visible { outline: 2px solid var(--bot-color-primary); outline-offset: 2px; }`);
}
if (sg.forms) {
  const f = sg.forms;
  L.push(`:where(.bot-ui) input:not([type=checkbox]):not([type=radio]), :where(.bot-ui) select, :where(.bot-ui) textarea { min-height: ${px(f.inputHeight)}; border: 1px solid ${cv(f.inputBorder)}; border-radius: ${px(f.inputRadius)}; padding: 0 14px; font: inherit; font-size: 16px; width: 100%; }`);
  L.push(`:where(.bot-ui) textarea { padding: 12px 14px; min-height: 120px; }`);
  L.push(`:where(.bot-ui) input:focus, :where(.bot-ui) select:focus, :where(.bot-ui) textarea:focus { outline: 2px solid ${cv(f.focusColor)}; outline-offset: 1px; }`);
}
L.push(`:where(.bot-ui) .bot-script { font-family: var(--bot-font-script, var(--bot-font-heading)); font-weight: 400; text-transform: none; }`);
L.push(`:where(.bot-ui) img { max-width: 100%; height: auto; display: block; }`);

const cssFile = path.join(theme, 'assets', 'bot-tokens.css');
fs.mkdirSync(path.dirname(cssFile), { recursive: true });
fs.writeFileSync(cssFile, L.join('\n') + '\n');

// Link the stylesheet once in layout/theme.liquid, just before </head>.
const layout = path.join(theme, 'layout', 'theme.liquid');
let linked = false;
if (fs.existsSync(layout)) {
  let html = fs.readFileSync(layout, 'utf8');
  if (!html.includes("'bot-tokens.css'")) {
    html = html.replace(/<\/head>/i, "    {{ 'bot-tokens.css' | asset_url | stylesheet_tag }}\n  </head>");
    fs.writeFileSync(layout, html);
  }
  linked = true;
}
console.log(`Wrote ${cfg.themeDir}/assets/bot-tokens.css${linked ? ' and linked it in layout/theme.liquid' : ' (layout/theme.liquid not found, link it manually)'}`);
